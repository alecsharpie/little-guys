// Tiny raster kit for the UI-kit painter (grid helpers adapted from tools/sprites/pests/kit.mjs).
// A grid is an array of rows of palette chars, '.' = transparent. Light from the upper-left.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
export const grid = (w, h, c = '.') => Array.from({ length: h }, () => Array(w).fill(c));
export const W = g => g[0].length, H = g => g.length;
export const get = (g, x, y) => (y >= 0 && y < g.length && x >= 0 && x < g[0].length) ? g[y][x] : '.';
export function put(g, x, y, c) { x = Math.round(x); y = Math.round(y); if (c && c !== '.' && y >= 0 && y < g.length && x >= 0 && x < g[0].length) g[y][x] = c; }
export function erase(g, x, y) { if (y >= 0 && y < g.length && x >= 0 && x < g[0].length) g[y][x] = '.'; }
export const clone = g => g.map(r => r.slice());
export const text = g => '\n' + g.map(r => r.join('')).join('\n') + '\n';
export const rows = s => (Array.isArray(s) ? s : s.replace(/^\n+|\n+$/g, '').split('\n'));

/** stamp ascii rows at (x,y); '.'/' ' transparent; map remaps chars */
export function stamp(g, x, y, art, map = null) {
  rows(art).forEach((r, j) => [...r].forEach((c, i) => { if (c === '.' || c === ' ') return; put(g, x + i, y + j, map && map[c] ? map[c] : c); }));
  return g;
}
export function over(a, b, dx = 0, dy = 0) {
  for (let y = 0; y < b.length; y++) for (let x = 0; x < b[0].length; x++) if (b[y][x] !== '.') put(a, x + dx, y + dy, b[y][x]);
  return a;
}
export function line(g, x0, y0, x1, y1, ch) {
  x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
  const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1; let err = dx + dy;
  for (; ;) { put(g, x0, y0, ch); if (x0 === x1 && y0 === y1) break; const e2 = 2 * err; if (e2 >= dy) { err += dy; x0 += sx; } if (e2 <= dx) { err += dx; y0 += sy; } }
}
export const maskOf = g => g.map(r => r.map(c => (c !== '.' ? 1 : 0)));
/** outline: every empty 4-neighbour (or 8 with diag) of a filled cell gets ink (string or fn(x,y,nb)) */
export function outline(g, ink, o = {}) {
  const m = o.mask || maskOf(g), add = [];
  for (let y = 0; y < g.length; y++) for (let x = 0; x < g[0].length; x++) {
    if (m[y][x]) continue;
    const dn = get(m, x, y + 1) === 1, rt = get(m, x + 1, y) === 1, up = get(m, x, y - 1) === 1, lf = get(m, x - 1, y) === 1;
    const dg = o.diag && [[1, 1], [-1, 1], [1, -1], [-1, -1]].some(([a, b]) => get(m, x + a, y + b) === 1);
    if (!dn && !rt && !up && !lf && !dg) continue;
    const c = typeof ink === 'function' ? ink(x, y, { dn, rt, up, lf }) : ink;
    if (c) add.push([x, y, c]);
  }
  for (const [x, y, c] of add) g[y][x] = c;
  return g;
}
export function shift(g, dx, dy) { const n = grid(W(g), H(g)); return over(n, g, dx, dy); }
export function recolor(g, map) { for (const r of g) for (let x = 0; x < r.length; x++) if (map[r[x]]) r[x] = map[r[x]]; return g; }

/** write sprites/<id>.js. notes: extra comment lines at the top (slice sizes etc.) */
export function emit(id, about, spec, notes = []) {
  const fr = Object.entries(spec.frames).map(([k, L]) => `    ${k}: [${L.map(t => '`' + (typeof t === 'string' ? t : text(t)) + '`').join(', ')}],`).join('\n');
  const pal = Object.entries(spec.palette).map(([k, v]) => `    ${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k)}: '${v}',`).join('\n');
  const extra = (spec.fps ? `  fps: ${JSON.stringify(spec.fps)},\n` : '') + (spec.slice ? `  slice: ${spec.slice},\n` : '');
  const src = `// @pixel ${id}: ${about}\n${notes.map(n => '// ' + n + '\n').join('')}// Generated by tools/sprites/ui.mjs (tools/sprites/ui/). Do not hand-edit: change the generator and re-run it.\nexport default {\n  id: '${id}', anchor: ${JSON.stringify(spec.anchor)},\n${extra}  palette: {\n${pal}\n  },\n  frames: {\n${fr}\n  },\n};\n`;
  for (const [set, L] of Object.entries(spec.frames)) {
    const gs = L.map(t => typeof t === 'string' ? t.replace(/^\n|\n$/g, '').split('\n') : t.map(r => r.join('')));
    const w = gs[0][0].length, h = gs[0].length;
    gs.forEach((rs, i) => { if (rs.length !== h || rs.some(r => r.length !== w)) throw new Error(`${id}.${set}[${i}] size mismatch`); rs.forEach(r => [...r].forEach(c => { if (c !== '.' && !(c in spec.palette)) throw new Error(`${id}.${set}[${i}] unknown char '${c}'`); })); });
  }
  fs.writeFileSync(path.join(ROOT, 'sprites', id + '.js'), src);
  return spec;
}
