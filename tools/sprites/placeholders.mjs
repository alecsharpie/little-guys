// Writes a stand-in sprite for every id in sprites/index.js that has no file yet (a flat coloured blob per frame),
// so the game runs before the art is painted. node tools/sprites/placeholders.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../sprites');
const IDS = {
  gardener: [16, 24, { idle: 4, walk: 8, bonk: 4, charge: 2, spin: 4, water: 4, dizzy: 4, sleep: 2, cheer: 2 }, 'T'],
  crop_carrot: [12, 16, { grow: 4, wilt: 1 }, 'g'], crop_cabbage: [12, 14, { grow: 4, wilt: 1 }, 'g'], crop_pumpkin: [16, 14, { grow: 4, wilt: 1 }, 'g'],
  crop_tomato: [12, 16, { grow: 4, wilt: 1 }, 'g'], crop_sunflower: [12, 22, { grow: 4, wilt: 1 }, 'g'], crop_strawberry: [12, 12, { grow: 4, wilt: 1 }, 'g'],
  plot: [60, 44, { soil: 4 }, 's', 'c'], grass: [32, 32, { idle: 3 }, 'G', 'tl'], tufts: [8, 6, { idle: 3 }, 'g'], flowers: [7, 7, { idle: 4 }, 'y'],
  stones: [8, 5, { idle: 2 }, 'k'], bush: [26, 20, { idle: 1 }, 'g'], shed: [56, 52, { idle: 1 }, 'w'], barrel: [16, 20, { idle: 1 }, 'w'],
  beetle: [12, 10, { walk: 4, munch: 2 }, 'b'], snail: [16, 12, { walk: 4, munch: 2, hide: 1 }, 'n'], hopper: [16, 11, { hop: 4, munch: 2 }, 'h'],
  stag: [18, 14, { walk: 4, munch: 2 }, 'm'], stinkbug: [12, 10, { walk: 4, munch: 2, fly: 2 }, 'u'], queen: [36, 28, { walk: 4, munch: 2, roar: 2 }, 'q'],
  ladybug: [11, 9, { fly: 2, walk: 2 }, 'r'], weed: [10, 12, { idle: 2 }, 'g'],
  fx_poof: [16, 16, { idle: 5 }, 'W', 'c'], fx_stink: [32, 22, { idle: 4 }, 'u', 'c'], fx_sparkle: [7, 7, { idle: 4 }, 'y', 'c'], fx_star: [5, 5, { idle: 4 }, 'y', 'c'],
  fx_bee: [7, 6, { fly: 2 }, 'y', 'c'], fx_drop: [3, 5, { drop: 1, splash: 3 }, 'B', 'c'],
};
const PAL = { T: 'team', g: '#5fb83f', s: '#7a4f33', G: '#6cbf55', y: '#ffd23f', k: '#9aa0a6', w: '#8a6a3a', b: '#3a5a3a', n: '#c99a6a', h: '#8ac040', m: '#334455', u: '#7a8a3a', q: '#4a2a6a', r: '#e03030', W: '#eeeeee', B: '#5ab0ff', o: '#24180f' };
for (const [id, [w, h, sets, ch, shape]] of Object.entries(IDS)) {
  const f = path.join(dir, id + '.js');
  if (fs.existsSync(f)) continue;
  const grid = k => '\n' + Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => {
    if (shape === 'tl') return ch;
    const dx = (x + 0.5 - w / 2) / (w / 2), dy = (y + 0.5 - h / 2 - (k % 2 ? 0.5 : 0)) / (h / 2), r = dx * dx + dy * dy;
    return r > 1 ? '.' : r > 0.7 ? 'o' : ch;
  }).join('')).join('\n') + '\n';
  const frames = Object.entries(sets).map(([s, n]) => `    ${s}: [${Array.from({ length: n }, (_, k) => '`' + grid(k) + '`').join(', ')}],`).join('\n');
  const anchor = shape === 'c' || shape === 'tl' ? [w >> 1, h >> 1] : [w >> 1, h];
  fs.writeFileSync(f, `// @placeholder ${id}: stand-in until it is painted\nexport default {\n  id: '${id}', anchor: ${JSON.stringify(anchor)},\n  palette: { ${ch}: '${PAL[ch]}', o: '#24180f' },\n  frames: {\n${frames}\n  },\n};\n`);
  console.log('placeholder', id);
}
const ids = Object.keys(IDS);
fs.writeFileSync(path.join(dir, 'index.js'), `// Every sprite, by id (see SPRITES.md). Generated by tools/sprites/placeholders.mjs; add new ids there.\n${ids.map(i => `import ${i} from './${i}.js';`).join('\n')}\nexport const S = { ${ids.join(', ')} };\n`);
